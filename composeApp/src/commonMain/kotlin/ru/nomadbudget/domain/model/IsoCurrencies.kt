    private val byCode: Map<String, IsoCurrency> = all.associateBy { it.code }

    fun find(code: String): IsoCurrency? = byCode[code.trim().uppercase()]

    fun nameOf(code: String): String? = find(code)?.name

    fun search(query: String, exclude: Set<String> = emptySet(), limit: Int = SEARCH_LIMIT): List<IsoCurrency> {
        val q = query.trim()
        if (q.isEmpty()) return emptyList()
        val upper = q.uppercase()
        val lower = q.lowercase()
        return all
            .asSequence()
            .filter { it.code !in exclude }
            .filter { it.code.startsWith(upper) || it.name.lowercase().contains(lower) }
            .sortedWith(compareBy({ !it.code.startsWith(upper) }, { it.code }))
            .take(limit)
            .toList()
    }

    private const val SEARCH_LIMIT = 8
}
